"""Import Google's classic Material palette and generate native Android theme resources.

Run without arguments to regenerate from the checked-in source data. --refresh
downloads the official table again. Neither path runs Gradle or compiles the app.
"""

import argparse
import colorsys
import gzip
import json
from pathlib import Path
import re
import urllib.request


ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tools/material_palette_source.json"
SOURCE_URL = "https://m1.material.io/style/color.html#color-color-palette"
NAMES = {
  "Red": "红色", "Pink": "粉色", "Purple": "紫色", "Deep Purple": "深紫色",
  "Indigo": "靛蓝色", "Blue": "蓝色", "Light Blue": "浅蓝色", "Cyan": "青色",
  "Teal": "蓝绿色", "Green": "绿色", "Light Green": "浅绿色", "Lime": "青柠色",
  "Yellow": "黄色", "Amber": "琥珀色", "Orange": "橙色", "Deep Orange": "深橙色",
  "Brown": "棕色", "Grey": "灰色", "Blue Grey": "蓝灰色", "Black": "黑色", "White": "白色",
}
TONES = ["50", "100", "200", "300", "400", "500", "600", "700", "800", "900", "A100", "A200", "A400", "A700"]


def refresh_source():
  with urllib.request.urlopen(SOURCE_URL, timeout=30) as response:
    data = response.read()
  if data[:2] == b"\x1f\x8b":
    data = gzip.decompress(data)
  groups = {}
  group = None
  for block in re.split(r'(?=<div class="color-tag\b)', data.decode("utf-8"))[1:]:
    name = re.search(r'<span class="group">([^<]+)</span>', block)
    shade = re.search(r'<span class="shade">([^<]+)</span>', block)
    color = re.search(r'<span class="hex">(#[0-9a-fA-F]{6})</span>', block)
    if not shade or not color:
      raise ValueError("The official palette markup changed")
    if name:
      group = name.group(1).strip()
    tone = shade.group(1).strip()
    if tone in ("Black", "White"):
      group = tone
    if group not in NAMES:
      raise ValueError(f"Unexpected official color family: {group}")
    colors = groups.setdefault(group, {})
    value = color.group(1).upper()
    if tone in colors and colors[tone] != value:
      raise ValueError(f"Conflicting official color: {group} {tone}")
    colors[tone] = value
  assert list(groups) == list(NAMES)
  assert sum(len(colors) for colors in groups.values()) == 256
  families = []
  for name, colors in groups.items():
    ordered = [name] if name in ("Black", "White") else [tone for tone in TONES if tone in colors]
    assert len(ordered) == len(colors)
    families.append({"name": name, "colors": {tone: colors[tone] for tone in ordered}})
  SOURCE.write_text(json.dumps({"sourceURL": SOURCE_URL, "families": families}, indent=2) + "\n", encoding="utf-8")


def luminance(value):
  channels = [int(value[index:index + 2], 16) / 255 for index in (1, 3, 5)]
  channels = [channel / 12.92 if channel <= 0.04045 else ((channel + 0.055) / 1.055) ** 2.4 for channel in channels]
  return sum(channel * weight for channel, weight in zip(channels, (0.2126, 0.7152, 0.0722)))


def contrast(first, second):
  a, b = sorted((luminance(first), luminance(second)))
  return (b + 0.05) / (a + 0.05)


def identifier(name, tone):
  family = name.lower().replace(" ", "_")
  return family if name in ("Black", "White") else f"{family}_{tone.lower()}"


def style_name(name, tone):
  suffix = name.replace(" ", "") + ("" if name in ("Black", "White") else tone)
  return f"ThemeOverlay.AutoClicker.Palette.{suffix}"


def color_from_hls(hue, lightness, saturation):
  channels = colorsys.hls_to_rgb(hue, lightness, saturation)
  return "#" + "".join(f"{round(channel * 255):02X}" for channel in channels)


def theme_colors(selected, night):
  channels = [int(selected[index:index + 2], 16) / 255 for index in (1, 3, 5)]
  hue, lightness, saturation = colorsys.rgb_to_hls(*channels)
  if night:
    # M2 dark themes use less saturated accents on neutral elevated surfaces.
    saturation = min(saturation, 0.5)
    lightness = max(lightness, 0.65)
  backgrounds = ("#121212", "#1E1E1E", "#272727", "#2C2C2C", "#383838") if night else ("#FFFFFF", "#FAFAFA", "#F5F5F5")
  foreground = "#000000" if night else "#FFFFFF"
  direction = 1 if night else -1
  for step in range(1001):
    candidate = color_from_hls(hue, min(1, max(0, lightness + direction * step / 1000)), saturation)
    if all(contrast(candidate, background) >= 4.5 for background in (*backgrounds, foreground)):
      return candidate, foreground
  raise ValueError(f"No readable accent for {selected}")


def write(relative, lines):
  path = ROOT / relative
  path.parent.mkdir(parents=True, exist_ok=True)
  path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def generate():
  data = json.loads(SOURCE.read_text(encoding="utf-8"))
  families = data["families"]
  assert len(families) == 21 and sum(len(family["colors"]) for family in families) == 256
  header = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tools/generate_material_palettes.py from the official Material color table. -->', '<resources>']
  colors_xml = header.copy()
  labels_xml = header.copy()
  styles = {False: header.copy(), True: header.copy()}
  kotlin = ["package com.roy.autoclicker.modules.theme", "", "import com.roy.autoclicker.R", "",
            "// 由 tools/generate_material_palettes.py 生成，色值来源见 material_palette_source.json。",
            "internal val GENERATED_MATERIAL_FAMILIES = listOf("]
  for family in families:
    name, colors = family["name"], family["colors"]
    family_id = name.lower().replace(" ", "_")
    labels_xml.append(f'    <string name="palette_{family_id}">{NAMES[name]}</string>')
    kotlin.append(f'  MaterialFamily("{family_id}", R.string.palette_{family_id}, listOf(')
    for tone, value in colors.items():
      key = identifier(name, tone)
      style = style_name(name, tone)
      bar_foreground = max(("#000000", "#FFFFFF"), key=lambda color: contrast(color, value))
      assert contrast(bar_foreground, value) >= 4.5
      colors_xml.append(f'    <color name="material_{key}">{value}</color>')
      kotlin.append(f'    MaterialSwatch("{key}", "{tone}", R.color.material_{key}, R.style.{style.replace(".", "_")}),')
      for night, output in styles.items():
        accent, foreground = theme_colors(value, night)
        items = {
          "android:colorPrimary": f"@color/material_{key}",
          "android:colorPrimaryDark": f"@color/material_{key}",
          "android:colorAccent": accent,
          "android:windowLightStatusBar": str("#000000" == bar_foreground).lower(),
          "color_app_bar": f"@color/material_{key}",
          "color_on_app_bar": bar_foreground,
          "color_app_bar_ripple": "#18000000" if "#000000" == bar_foreground else "#33FFFFFF",
          "color_action": accent,
          "color_button_background": accent,
          "color_on_button": foreground,
          "color_button_ripple": "#30FFFFFF" if "#FFFFFF" == foreground else "#18000000",
        }
        output.append(f'    <style name="{style}" parent="">')
        output.extend(f'        <item name="{attribute}">{color}</item>' for attribute, color in items.items())
        output.append('    </style>')
    kotlin.append('  )),')
  kotlin.append(')')
  for lines in [colors_xml, labels_xml, *styles.values()]:
    lines.append('</resources>')
  write('app/src/main/res/values/material_colors.xml', colors_xml)
  write('app/src/main/res/values/material_palette_labels.xml', labels_xml)
  write('app/src/main/res/values/material_palette_themes.xml', styles[False])
  write('app/src/main/res/values-night/material_palette_themes.xml', styles[True])
  write('app/src/main/java/com/roy/autoclicker/modules/theme/MaterialPaletteData.kt', kotlin)
  print('Generated 256 official colors, 21 color families, and 256 light/dark theme overlays.')


if __name__ == "__main__":
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument('--refresh', action='store_true')
  if parser.parse_args().refresh:
    refresh_source()
  generate()
